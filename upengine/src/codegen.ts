import { $ } from "bun";
import { join } from "node:path";
import { MODULES_DIR, ROOT_DIR } from "./paths.ts";
import type { ImageRef } from "./types.ts";

/**
 * Renders a module's generated templates/versions.cue holding the image
 * defaults tracked from the upstream releases. Key order follows the
 * sources.yaml declaration; the output is already in canonical timoni fmt
 * form (tabs, aligned by `timoni fmt` afterwards as a safety net).
 */
export function renderVersionsCue(images: Map<string, ImageRef>): string {
  const lines = [
    "// Code generated by upengine. DO NOT EDIT.",
    "",
    "package templates",
    "",
    "// The container images tracked from the upstream releases.",
    "#defaultImages: {",
  ];
  for (const [key, ref] of images) {
    lines.push(`\t"${key}": {`);
    lines.push(`\t\trepository: "${ref.repository}"`);
    lines.push(`\t\ttag:        "${ref.tag}"`);
    lines.push(`\t\tdigest:     "${ref.digest}"`);
    lines.push("\t}");
  }
  lines.push("}", "");
  return lines.join("\n");
}

/** Writes the generated files of a module bump: versions.cue and VERSION. */
export async function writeModuleFiles(
  name: string,
  images: Map<string, ImageRef>,
  moduleVersion: string,
): Promise<void> {
  const moduleDir = join(MODULES_DIR, name);
  await Bun.write(join(moduleDir, "templates/versions.cue"), renderVersionsCue(images));
  await Bun.write(join(moduleDir, "VERSION"), `${moduleVersion}\n`);
  await $`timoni fmt ${join(moduleDir, "templates")}`.cwd(ROOT_DIR).quiet();
}

/**
 * Post-bump guards: the module must vet clean with the debug values (which
 * enable every optional object) and render non-empty manifests with the
 * defaults. Failures surface the tool output.
 */
export async function verifyModule(name: string): Promise<void> {
  const moduleDir = join(MODULES_DIR, name);
  await run(["timoni", "mod", "vet", moduleDir, "--debug"]);
  const build = await run(["timoni", "-n", name, "build", name, moduleDir]);
  if (!build.includes("kind:")) {
    throw new Error(`timoni build of ${name} produced no resources`);
  }
}

async function run(argv: string[]): Promise<string> {
  const proc = Bun.spawn(argv, { cwd: ROOT_DIR, stdout: "pipe", stderr: "pipe" });
  const [stdout, stderr, exitCode] = await Promise.all([
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
    proc.exited,
  ]);
  if (exitCode !== 0) {
    throw new Error(`${argv.join(" ")} failed:\n${stderr || stdout}`);
  }
  return stdout;
}
